type ProfileThemeStyle = CSSProperties & Record<`--profile-${'dark' | 'light'}-${string}`, string>

export function profileThemeStyle(preset: ProfileAppearancePreset): ProfileThemeStyle {
  const definition = PROFILE_THEME_TOKENS[preset]
  const style = {} as ProfileThemeStyle
  for (const mode of ['light', 'dark'] as const) {
    for (const token of PROFILE_THEME_TOKEN_KEYS)
      style[`--profile-${mode}-${TOKEN_CSS_NAMES[token]}`] = definition[mode][token]
  }
  return style
}

